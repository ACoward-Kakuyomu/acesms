#pragma once
#include <cstdint>
#include <initializer_list>
#include <vector>

namespace smsgg::test {
inline std::vector<uint8_t> stage6AudioRom() {
    std::vector<uint8_t> rom(8192);
    size_t at=0;
    auto emit=[&](std::initializer_list<uint8_t> bytes) {for(auto b:bytes) rom[at++]=b;};
    auto out=[&](uint8_t port,uint8_t value) {emit({0x3e,value,0xd3,port});};
    auto address=[&](uint16_t a,uint8_t code) {out(0xbf,static_cast<uint8_t>(a));out(0xbf,static_cast<uint8_t>((a>>8)|(code<<6)));};
    auto reg=[&](uint8_t n,uint8_t v) {out(0xbf,v);out(0xbf,0x80|n);};
    auto jump=[&](uint8_t opcode=0xc3) {emit({opcode,0,0});return at-2;};
    auto patch=[&](size_t position,size_t target) {rom[position]=static_cast<uint8_t>(target);rom[position+1]=static_cast<uint8_t>(target>>8);};
    emit({0xc3,0x00,0x01});
    at=0x38;
    emit({0xf5,0xe5,0xdb,0xbf,0x21,0x00,0xc0,0x34,0xe1,0xf1,0xfb,0xed,0x4d});
    at=0x66;
    emit({0xf5,0x3a,0x01,0xc0,0x3c,0x32,0x01,0xc0,0xf1,0xed,0x45});
    at=0x100;
    emit({0xf3,0x31,0xf8,0xdf,0x3e,0xff,0x32,0x05,0xc0});
    reg(0,4);reg(2,0x0e);reg(5,0x7e);
    address(0,1);
    for(unsigned row=0;row<8;++row) {out(0xbe,row%2?0x55:0xaa);out(0xbe,row%2?0xaa:0x55);out(0xbe,0);out(0xbe,0);}
    address(0,3);out(0xbe,0);out(0xbe,3);out(0xbe,0x30);
    address(0x3f00,1);out(0xbe,0xd0);
    reg(1,0x60);emit({0xed,0x56,0xfb});
    const auto loop=at;
    emit({0x76,0xdb,0xdc,0x32,0x02,0xc0,0xe6,0x3f,0xfe,0x3f,0x3e,0x01});
    const auto pressed=jump(0xc2); // Any ordinary input selects tone 1.
    emit({0x3a,0x00,0xc0,0x07,0x07,0xe6,0x03});
    patch(pressed,at);
    emit({0x47,0x3a,0x02,0xc0,0xe6,0x20,0x20,0x02,0x06,0x04,
        0x3a,0x02,0xc0,0xe6,0x01,0x20,0x02,0x06,0x05,
        0x3a,0x02,0xc0,0xe6,0x02,0x20,0x02,0x06,0x06,
        0x3a,0x01,0xc0,0xe6,0x01,0x28,0x02,0x06,0x03,
        0x78,0x32,0x04,0xc0,0x3a,0x05,0xc0,0xb8});
    const auto unchanged=jump(0xca);
    emit({0x78,0x32,0x05,0xc0});
    for(const uint8_t value:{0x9f,0xbf,0xdf,0xff}) out(0x7f,value);
    std::vector<size_t> branches;
    for(uint8_t stage=0;stage<7;++stage) {emit({0x78,0xfe,stage});branches.push_back(jump(0xca));}
    std::vector<size_t> drawJumps;
    for(unsigned stage=0;stage<7;++stage) {
        patch(branches[stage],at);
        if(stage==0) {out(0x7f,0x8e);out(0x7f,0x0f);out(0x7f,0x90);}
        if(stage==1) {out(0x7f,0xac);out(0x7f,0x1f);out(0x7f,0xb0);}
        if(stage==2) {out(0x7f,0xe5);out(0x7f,0xf0);}
        if(stage==4) {out(0x7f,0xcf);out(0x7f,0x07);out(0x7f,0xd0);}
        if(stage==5) {out(0x7f,0xe2);out(0x7f,0xf0);}
        if(stage==6) {out(0x7f,0x81);out(0x7f,0);}
        drawJumps.push_back(jump());
    }
    const auto draw=at;
    patch(unchanged,draw);for(auto position:drawJumps) patch(position,draw);
    emit({0x3a,0x04,0xc0,0xfe,0x06});
    const auto notVolume=jump(0xc2);
    emit({0x3a,0x00,0xc0,0xe6,0x0f,0xf6,0x90,0xd3,0x7f});
    patch(notVolume,at);
    emit({0x21,0,0});const auto tableAddress=at-2;
    emit({0x3a,0x04,0xc0,0x5f,0x16,0,0x19,0x46});
    address(1,3);emit({0x78,0xd3,0xbe});
    const auto again=jump();patch(again,loop);
    patch(tableAddress,at);emit({0x03,0x0c,0x0f,0x3f,0x33,0x3c,0x15});
    return rom;
}
} // namespace smsgg::test
