#include "core/audio/Psg.h"

#include <array>
#include <iostream>
#include <string_view>

namespace {
using namespace smsgg;
bool same(const PsgState& a,const PsgState& b) {
    return a.tones==b.tones && a.volumes==b.volumes && a.counters==b.counters && a.outputs==b.outputs
        && a.selected==b.selected && a.noise==b.noise && a.stereo==b.stereo && a.divider==b.divider
        && a.noiseCounter==b.noiseCounter && a.lfsr==b.lfsr && a.noisePhase==b.noisePhase && a.noiseOutput==b.noiseOutput;
}
bool latches() {
    for(unsigned selected=0;selected<8;++selected) for(unsigned mask=0;mask<256;++mask) {
        Psg original,restored;
        for(unsigned ch=0;ch<3;++ch) {
            original.write(static_cast<uint8_t>(0x80|(ch<<5)|ch));
            original.write(static_cast<uint8_t>(ch==2?63:0));
            original.write(static_cast<uint8_t>(0x90|(ch<<5)|ch));
        }
        original.write(0xe7);original.write(0xf3);original.writeStereo(static_cast<uint8_t>(mask));
        original.advance(1171);
        original.write(static_cast<uint8_t>(0x80|(selected<<4)|5));
        const auto saved=original.captureState();
        if(saved.selected!=selected || saved.stereo!=mask || saved.divider!=3) return false;
        restored.write(0x90);restored.advance(7000);restored.writeStereo(0);
        restored.restoreState(saved);
        if(!same(saved,restored.captureState())) return false;
        original.write(0x2a);restored.write(0x2a);
        const auto after=restored.captureState();
        if(selected&1) { if(after.volumes[selected>>1]!=10) return false; }
        else if(selected==6) { if(after.noise!=2 || after.lfsr!=0x8000) return false; }
        else if(after.tones[selected>>1]!=0x2a5) return false;
        for(uint64_t delta:{0ull,1ull,12ull,16ull,113ull,3001ull}) {
            const auto a=original.advance(delta),b=restored.advance(delta);
            if(a.left!=b.left || a.right!=b.right || !same(original.captureState(),restored.captureState())) return false;
        }
        // The saved value does not follow either device's later mutations.
        restored.restoreState(saved);
        if(!same(saved,restored.captureState()) || saved.divider!=3 || saved.selected!=selected) return false;
    }
    return true;
}
bool phase() {
    // Fixed white-noise sequence around its 16th rising edge (not generated by capture/restore).
    for(unsigned mode=0;mode<8;++mode) for(unsigned offset=0;offset<16;++offset) {
        Psg original,restored;
        original.write(0xc2);original.write(0);original.write(static_cast<uint8_t>(0xe0|mode));
        const unsigned half=(mode&3)==3?32:256u<<(mode&3);
        const uint64_t before=(mode&3)==3?16+30*32:31*half;
        original.advance(before-16+offset);
        const auto saved=original.captureState();
        const auto prior=(mode&4)?0x2001:0x0001;
        if(saved.lfsr!=prior || saved.divider!=offset) return false;
        restored.advance(9999);restored.restoreState(saved);
        const auto a=original.advance(16-offset),b=restored.advance(16-offset);
        const auto expected=(mode&4)?0x9000:0x8000;
        if(a.left!=0 || a.right!=0 || b.left!=0 || b.right!=0
            || restored.captureState().lfsr!=expected || !restored.captureState().noiseOutput
            || !same(original.captureState(),restored.captureState())) return false;
        // Muted advancement still updates the clock. Unmute the held noise at full volume.
        original.write(0xf0);restored.write(0xf0);
        original.writeStereo(0x80);restored.writeStereo(0x80);
        const auto left=restored.advance(7),ref=original.advance(7);
        if(left.left!=1.75 || left.right!=0 || left.left!=ref.left || !same(original.captureState(),restored.captureState())) return false;
        if(saved.lfsr!=prior || saved.noiseOutput) return false;
    }
    // Save one T-state before the first tone edge and resume both half periods.
    for(unsigned period:{2u,1023u}) {
        Psg original,restored;
        original.write(static_cast<uint8_t>(0x80|(period&15)));original.write(static_cast<uint8_t>(period>>4));original.write(0x90);
        if(original.advance(15).left!=-3.75) return false;
        const auto saved=original.captureState();restored.restoreState(saved);
        if(restored.advance(1).left!=-.25 || restored.advance(period*16).left!=period*4.0
            || restored.advance(period*16).left!=-static_cast<double>(period)*4.0) return false;
    }
    return true;
}
bool clockState() {
    for(uint32_t c:{3579545u,3546893u}) for(uint32_t r:{44100u,48000u,96000u}) {
        for(uint64_t n:{1ull,2ull,173ull,1000003ull}) for(unsigned edge=0;edge<2;++edge) {
            const auto at=(n*c+r-1)/r-1+edge;
            AudioClock original(c,r),restored(c,r);
            if(original.advance(at)!=at*r/c) return false;
            const auto saved=original.captureState();
            if(saved.phase!=at*r%c) return false;
            restored.advance(uint64_t(c)*3600+99);restored.restoreState(saved);
            uint64_t time=at;
            for(uint64_t delta:{0ull,1ull,17ull,999ull,123456789ull}) {
                const auto expected=(time+delta)*r/c-time*r/c;
                if(original.advance(delta)!=expected || restored.advance(delta)!=expected) return false;
                time+=delta;
                const auto phase=time*r%c;
                if(original.captureState().phase!=phase || restored.captureState().phase!=phase
                    || restored.tstatesToSample()!=(c-phase+r-1)/r || original.tstatesToSample()!=restored.tstatesToSample()) return false;
            }
            restored.restoreState(saved);
            if(restored.captureState().phase!=saved.phase || saved.phase!=at*r%c) return false;
        }
        AudioClock longClock(c,r),restored(c,r);
        const uint64_t at=uint64_t(c)*3600+12345;
        if(longClock.advance(at)!=uint64_t(r)*3600+uint64_t(12345)*r/c) return false;
        const auto saved=longClock.captureState();restored.restoreState(saved);
        if(saved.phase!=uint64_t(12345)*r%c || restored.advance(1)!=longClock.advance(1)) return false;
    }
    return true;
}
}
int main(int argc,char** argv) {
    const std::string_view name=argc==2?argv[1]:"";
    const bool pass=name=="latches"?latches():name=="phase"?phase():name=="clock"&&clockState();
    if(!pass) std::cerr<<"Audio state failed: "<<name<<'\n';
    return pass?0:1;
}
